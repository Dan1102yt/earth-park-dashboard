// En los trazos de arriba, "Mx y aRX RY 0 1 0 0.01 0" significa: elipse cuyo punto más alto es (x, y).
// Los canvas no siempre dibujan bien un arco de casi 360°, así que lo convertimos en dos medios arcos.
const CIRCULO = /M\s*([\d.]+)\s+([\d.]+)\s*a\s*([\d.]+)\s+([\d.]+)\s+0\s+1\s+0\s+0\.01\s+0/g;
