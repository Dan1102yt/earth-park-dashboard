-- ── Catálogo: una fila por actividad que se puede cotizar ──
-- unidad: persona | persona_noche | persona_dia (se suma una vez por día) | grupo_dia (un valor para todo el grupo)
CREATE TABLE IF NOT EXISTS catalogo (
  codigo          text        PRIMARY KEY,
  actividad       text        NOT NULL,
  unidad          text        NOT NULL DEFAULT 'persona',
  precio          integer     NOT NULL DEFAULT 0,
  costo           integer,                       -- null = falta el dato
  nota            text,
  activo          boolean     NOT NULL DEFAULT true,
  orden           integer     NOT NULL DEFAULT 0,
  actualizado_at  timestamptz NOT NULL DEFAULT now(),
  actualizado_por text
);

-- ── Planes que se venden (solo 3: pasadía, 2 días 1 noche, 3 días 2 noches) ──
-- itinerario: [["DES","EXP",...], ["DES",...]]  → un arreglo de códigos por día
-- fotos:      { "portada": url, "dias": [url, url], "tira": [url, url, url] }
CREATE TABLE IF NOT EXISTS planes_venta (
  id                text        PRIMARY KEY,
  nombre            text        NOT NULL,
  subtitulo         text,
  dias              integer     NOT NULL DEFAULT 1,
  noches            integer     NOT NULL DEFAULT 0,
  precio_referencia integer,                     -- precio por persona publicado en la web (solo para comparar)
  itinerario        jsonb       NOT NULL DEFAULT '[]',
  fotos             jsonb       NOT NULL DEFAULT '{}',
  mensaje           text,                        -- saludo que trae por defecto la propuesta
  activo            boolean     NOT NULL DEFAULT true,
  orden             integer     NOT NULL DEFAULT 0,
  actualizado_at    timestamptz NOT NULL DEFAULT now()
);

-- ── Descuentos por tipo de cliente ──
CREATE TABLE IF NOT EXISTS descuentos_cliente (
  id          text    PRIMARY KEY,
  nombre      text    NOT NULL,
  porcentaje  numeric NOT NULL DEFAULT 0,        -- 0.10 = 10 %
  nota        text,
  orden       integer NOT NULL DEFAULT 0
);

-- ── Cotizaciones ──
-- estado: borrador → aprobada → enviada → reservada   (o descartada)
-- items guarda el precio y el costo del momento: si mañana cambia el catálogo, la cotización no cambia.
CREATE TABLE IF NOT EXISTS cotizaciones (
  id             uuid        DEFAULT gen_random_uuid() PRIMARY KEY,
  numero         integer     GENERATED BY DEFAULT AS IDENTITY (START WITH 61) UNIQUE,
  estado         text        NOT NULL DEFAULT 'borrador',
  cliente        jsonb       NOT NULL DEFAULT '{}',   -- { nombre, telefono, origen }
  adultos        integer     NOT NULL DEFAULT 2,
  ninos5         integer     NOT NULL DEFAULT 0,      -- niños de 5 años o más (pagan)
  menores5       integer     NOT NULL DEFAULT 0,      -- menores de 5 (no pagan)
  plan_id        text,
  llegada        date,
  tipo_cliente   text,
  descuento      numeric     NOT NULL DEFAULT 0,
  incluir_guia   boolean     NOT NULL DEFAULT true,
  dias_guia      integer     NOT NULL DEFAULT 1,
  items          jsonb       NOT NULL DEFAULT '[]',   -- [{ dia, codigo, actividad, unidad, precio, costo }]
  fotos          jsonb       NOT NULL DEFAULT '{}',
  mensaje        text,
  totales        jsonb       NOT NULL DEFAULT '{}',
  origen         text        NOT NULL DEFAULT 'panel', -- panel | whatsapp
  pdf_url        text,
  creado_por     text,
  creado_at      timestamptz NOT NULL DEFAULT now(),
  actualizado_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cotizaciones_estado ON cotizaciones (estado, creado_at DESC);

ALTER TABLE catalogo           ENABLE ROW LEVEL SECURITY;
